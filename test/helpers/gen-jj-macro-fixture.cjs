'use strict';
// GENERATOR (run manually; NOT a test) for the macro-fidelity fixture. It runs JJ's ORIGINAL simulation
// once from the seed-42 pool, records the initial pool AND JJ's macro trajectory (population / live-food /
// food-eaten at checkpoints), and writes it to test/fixtures/jj-macro-seed42.json. The committed test
// (world-macro-fidelity.test.js) then loads this frozen fixture and compares the CURRENT engine against it
// WITHOUT executing JJ -- so JJ's slow sim runs here once, not on every `node --test`.
//
// Re-run only to refresh the baseline (e.g. if JJ's code or the boot seed changes):
//   node test/helpers/gen-jj-macro-fixture.cjs

const fs = require('node:fs');
const path = require('node:path');
const { boot } = require('./boot');

const SEED = 42;
// Early POINT-IN-TIME checkpoints: tight & phase-insensitive (the two runs share a start, so they stay
// close before RNG divergence sets in) -- fast detection of immediate breakage.
const POINT_CHECKPOINTS = [500, 1000, 2000];
// Long-horizon signal: TIME-AVERAGED pop/food over MAX ticks. Point-in-time comparison at 10k is phase-
// sensitive (each engine runs its own boom-bust cycle; they drift out of phase -> ~10% instantaneous gap),
// but the time-average is phase-INsensitive and stays ~5% -- so that's what we compare at the long horizon.
const MAX = 10000;
const OUT = path.join(__dirname, '..', 'fixtures', 'jj-macro-seed42.json');

const gp = boot(SEED);
const pd0 = gp.getPoolData();
const obstacle = [pd0.obstacleEnd1X, pd0.obstacleEnd1Y, pd0.obstacleEnd2X, pd0.obstacleEnd2Y];

// initial pool -- genes base64'd (256 bytes -> ~344 chars) to keep the file small. Array.from copies the
// LIVE gene buffer JJ clobbers in place on slot-reuse births (the p1a-golden gotcha).
const swimbots = pd0.swimbotArray.map((s) => ({
    id: s.id, age: s.age, x: s.x, y: s.y, angle: s.angle, energy: s.energy,
    genes: Buffer.from(Array.from(s.genes)).toString('base64'),
    numOffspring: s.numOffspring, numFoodBitsEaten: s.numFoodBitsEaten,
}));
const food = pd0.foodBitArray.map((f) => ({ id: f.id, x: f.x, y: f.y, type: f.type }));

const points = {};
let popSum = 0, foodSum = 0;
for (let t = 1; t <= MAX; t++) {
    gp.update();
    const pd = gp.getPoolData();
    popSum += pd.swimbotArray.length;
    foodSum += pd.foodBitArray.length;
    if (POINT_CHECKPOINTS.includes(t)) {
        points[t] = {
            pop: pd.swimbotArray.length,
            food: pd.foodBitArray.length,
            eaten: pd.swimbotArray.reduce((a, s) => a + s.numFoodBitsEaten, 0),      // foraging signal
            offspring: pd.swimbotArray.reduce((a, s) => a + s.numOffspring, 0),      // mating signal
        };
    }
}

const fixture = {
    _comment: 'JJ original-sim macro baseline from boot(seed 42). Generated by test/helpers/gen-jj-macro-fixture.cjs. The test (world-macro-fidelity.test.js) compares the CURRENT engine to this within tolerance bands. NOT bit-for-bit: the engine deliberately diverges from JJ since P1b -- this checks the whole-pool ecosystem stays in JJ ballpark.',
    seed: SEED,
    config: {
        maximumLifeSpan: 40000, numFoodTypes: 1, childEnergyRatio: 0.5, hungerThreshold: 50,
        crossoverRate: 0.2, mutationRate: 0.01, foodRegenerationPeriod: 20, foodSpread: 4000,
        foodBitEnergy: 50, attractionCriterion: 10,
    },
    obstacle,
    pointCheckpoints: POINT_CHECKPOINTS,
    points,                                   // phase-insensitive early snapshots
    maxTick: MAX,
    avgPop: popSum / MAX,                      // phase-insensitive long-horizon signal
    avgFood: foodSum / MAX,
    init: { swimbots, food },
};

fs.writeFileSync(OUT, JSON.stringify(fixture));
const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log(`wrote ${OUT} (${kb} KB)`);
console.log('JJ points:', JSON.stringify(points));
console.log(`JJ avg over ${MAX}: pop=${(popSum / MAX).toFixed(1)} food=${(foodSum / MAX).toFixed(1)}`);
